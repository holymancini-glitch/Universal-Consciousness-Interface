"""
IIT (Integrated Information Theory) Calculator

Implements φ (phi) calculation based on Integrated Information Theory.
Measures the amount of integrated information generated by a system.

References:
- Tononi, G. (2004). An information integration theory of consciousness.
- Oizumi, M., et al. (2014). From the phenomenology to the mechanisms of consciousness.
"""

import asyncio
from typing import Dict, List, Tuple, Optional, Set
